// Общее для частей редактора: открытый документ, клетка под курсором, сообщение в панели и обновление курсора. Части
// (инструменты, файл, ввод) берут это отсюда, а не друг у друга — так между ними нет круговых зависимостей.

import { type MessageArgs, type MessageKey, t } from '@shared/i18n';
import type { Doc } from './doc';
import { ed } from './state';

export const session = {
    /** Открытая карта (до первой загрузки — нет). */
    doc: null as Doc | null,
    /** Клетка под курсором. */
    hover: null as number | null,
    /** Перерисовать курсор, след кисти или выделение и подсказку клетки (задаёт main.ts: знает текущий инструмент). */
    refresh: (): void => {},
    /** Клетки поменялись или открыта другая карта: пересобрать подписи уровней (задаёт main.ts). */
    levels: (): void => {},
    /** После отмены или повтора: выделенная сущность могла поменяться (задаёт инструмент «Объекты»). */
    restored: (): void => {},
};

/** Сообщение в панели слева: переводится сейчас, на текущий язык. */
export function report(key: MessageKey, args: MessageArgs = [], error = false): void {
    ed.status = t(key, args);
    ed.error = error;
}
