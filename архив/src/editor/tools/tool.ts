// Инструмент редактора: что он делает на ЛКМ, щелчке ПКМ, движении курсора и отпускании, какие клетки подсвечивает и какие
// клавиши берёт себе. main.ts передаёт ввод текущему инструменту; новый инструмент — новый файл здесь и строка в tools/index.ts.

export interface EditorTool {
    /** ЛКМ нажата (протяжка и отпускание — move и up). */
    down?(e: PointerEvent): void;
    /** Щелчок ПКМ (без протяжки: протяжка ПКМ — сдвиг камеры). */
    rightClick?(e: PointerEvent): void;
    /** Курсор двигается; `cell` — клетка под ним (по полю). */
    move?(e: PointerEvent, cell: number | null): void;
    /** ЛКМ отпущена. */
    up?(): void;
    /** Курсор ушёл с поля. */
    leave?(): void;
    /** Клетки, которые подсветить серебряной рамой (след кисти, выделение), когда курсор на `cell`. */
    area(cell: number | null): number[];
    /** Клавиша (без Ctrl); true — инструмент её забрал. */
    key?(e: KeyboardEvent): boolean;
    /** Выбрали другой инструмент: убрать своё с поля (подсказки и т. п.). */
    deactivate?(): void;
    /** Идёт мазок или перенос: отмена ждёт отпускания. */
    busy?(): boolean;
}
