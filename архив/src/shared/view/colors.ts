// Цвета команд: одно место и для подсветки поля, и для юнитов. Глаз куда чувствительнее к зелёному, чем к красному, поэтому
// чистый зелёный при той же «силе» выглядит почти вдвое ярче оранжевого (а блум, который срабатывает по яркости, ещё и сильнее
// его размывает). Цвета выравниваются по воспринимаемой яркости оранжевого: оттенок свой, а светят одинаково.

import * as THREE from 'three';

import type { Team } from '../core/entity';

export type { Team };

/** Воспринимаемая яркость (относительная, по линейным каналам): так её считает глаз, зелёный весит больше всех. */
function luminance(c: THREE.Color): number {
    return 0.2126 * c.r + 0.7152 * c.g + 0.0722 * c.b;
}

/** Опорный цвет, под чью яркость подгоняются остальные: оранжевый своих. */
const REFERENCE = new THREE.Color(0xff8a2a);

/** Тот же оттенок, но с яркостью опорного (только вниз: ярче опорного не делаем, чтобы не выйти за 1). */
function evenly(hex: number): number {
    const c = new THREE.Color(hex);
    return c.multiplyScalar(Math.min(1, luminance(REFERENCE) / luminance(c))).getHex();
}

/** Зелёный курсора и индикатора выбранного юнита: «вот здесь выбор» (цвет не команды, чтобы не путать с радиусами). */
export const SELECT_GREEN = 0x4cff72;

/** Пурпурный — акцент траекторий: линия прицела и рамка высоты вертолёта (то, что связано с полётом выстрела и положением в воздухе). */
export const TRAJECTORY_COLOR = 0xc84dff;

/** Радиус хода: бирюзовый, как во FM3 (первый слой подсветки; второй, радиус атаки, оранжевый). Яркость выровнена по оранжевому. */
export const MOVE_COLOR = evenly(0x2bc4e0);

/** Оранжевый: враги и радиус атаки (опасность, опорный цвет яркости). */
export const ORANGE = evenly(0xff8a2a);

/** Две команды: свои синие, враги оранжевые (третьего цвета, красного, не вводим: гамма чище); нейтралы холодно-серые (не свои и не враги). */
export const TEAM_COLOR: Record<Team, number> = {
    ally: evenly(0x4aa3ff),
    enemy: ORANGE,
    neutral: evenly(0xb8c6d6),
};
