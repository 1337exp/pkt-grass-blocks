// Общие для материалов поля uniform: размер кадра и плотность экрана (затухание линий к краям, толщина в пикселях), толщина
// линий, цвета сетки и краёв. У каждого поля свои объекты (два поля на странице не делят настройки). Это принятый стиль
// (STYLE.md); пробные варианты вида (узоры сетки, голубой цвет, толщины, засечки, швы, стили курсора и пути, слои воды) —
// в archive/2026-10-view-variants.

import * as THREE from 'three';

/** Голубой развёртки (полоса, медленно идущая по карте). */
export const GRID_LINE = new THREE.Color(0x3fb8ff);
/** Нейтрально-серая сетка: на почти чёрном серое читается ярко, поэтому тёмное (это уже «прозрачность»). */
const GRID_GRAY = new THREE.Color(0x8a9099).multiplyScalar(0.62);
/** Яркость крестика сетки в шейдере сетки: доля линии (0,32) на усиление у узла (1,35). Края уступов — в цвет и яркость крестиков. */
const CROSS_OPACITY = 0.32 * 1.35;

export class Look {
    /** Размер кадра (пиксели буфера) и пикселей буфера в пикселе экрана: для сетки, лент, подсветки, курсора. */
    readonly view = {
        uRes: { value: new THREE.Vector2(1, 1) },
        uPx: { value: 1 },
    };
    /** Толщина линий поля в пикселях экрана: все по 1 px. */
    readonly lineW = { value: 1 };
    /** Цвет точек и крестиков сетки; края уступов и вертикали — того же цвета и яркости. */
    readonly gridColor = { value: GRID_GRAY.clone() };
    readonly edgeColor = { value: GRID_GRAY.clone() };
    readonly edgeOpacity = { value: CROSS_OPACITY };

    /** Размер кадра в пикселях буфера и пикселей буфера в пикселе экрана. */
    setResolution(w: number, h: number, px = 1): void {
        this.view.uRes.value.set(w, h);
        this.view.uPx.value = px;
    }
}
