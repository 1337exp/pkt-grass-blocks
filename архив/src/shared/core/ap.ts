// Очки действия, ОД (AP во FM3; COMBAT.md, «Очки действия»): у бойца пул, который тратят ход и атака. У бойца два числа: предел пула
// (`apMax`, от 12 до 30) и подзарядка (`apCharge`, от 12 до 15): в начале своего хода боец получает подзарядку, но не больше предела.
// Потратил всё — вырастет только на подзарядку; чтобы накопить до предела, надо пропускать действия. Цены: ход — цена пути, атака —
// цена оружия (`Weapon.ap`). Только правила, без графики.

/** Предел и подзарядка нового бойца (во FM3 на старте оба 12). */
export const AP_START = 12;
/** Жёсткие потолки в игре: предел пула 30, подзарядка 15. */
export const AP_MAX_CAP = 30;
export const AP_CHARGE_CAP = 15;

/** Пул в начале хода: остаток плюс подзарядка, не больше предела. */
export const chargeAp = (ap: number, charge: number, max: number): number => Math.min(max, ap + charge);
